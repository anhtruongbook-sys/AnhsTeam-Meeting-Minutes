/**
 * Động cơ Tự Động Hóa Toàn Trình: Giải mã tệp âm thanh có sẵn (.m4a, .mp3, .wav, .aac, .ogg) ->
 * Chia đoạn giọng nói (VAD) -> Tự động gỡ băng (Speech-to-Text qua luồng ống ParcelFileDescriptor API 33+) ->
 * Tự động bóc tách Lượt phát biểu, Kết luận & Bảng phân công nhiệm vụ -> Tự động sinh Biên bản Word (.docx).
 */
class AutoAudioMinutesProcessor(private val context: Context) {

    data class SpeechChunk(
        val index: Int,
        val startSec: Int,
        val endSec: Int,
        val byteOffset: Long,
        val byteLength: Int
    )

    @Volatile
    var isProcessing: Boolean = false
        private set

    @Volatile
    var cancelRequested: Boolean = false
        private set

    @Volatile
    var progressPercent: Int = 0
        private set

    @Volatile
    var statusMessage: String = ""
        private set

    @Volatile
    var currentPartialText: String = ""
        private set

    @Volatile
    var sourceAudioName: String = ""
        private set

    @Volatile
    var sourceAudioDurationSec: Int = 0
        private set

    @Volatile
    var autoGeneratedDocxPath: String = ""
        private set

    val transcribedTurns = CopyOnWriteArrayList<Map<String, String>>()
    val extractedConclusions = CopyOnWriteArrayList<String>()
    val extractedActions = CopyOnWriteArrayList<Map<String, String>>()

    private var workerThread: Thread? = null
    private val mainHandler = Handler(Looper.getMainLooper())

    fun stopProcessingEarly() {
        if (isProcessing) {
            cancelRequested = true
            statusMessage = "Đang hoàn tất và tổng hợp biên bản từ các đoạn đã gỡ băng..."
        }
    }

    fun startAutoProcessAudioFile(
        audioFile: File,
        localeCode: String,
        docLanguageMode: String,
        minutesOutputDir: File
    ) {
        if (isProcessing) return
        isProcessing = true
        cancelRequested = false
        progressPercent = 2
        sourceAudioName = audioFile.name
        autoGeneratedDocxPath = ""
        currentPartialText = ""
        transcribedTurns.clear()
        extractedConclusions.clear()
        extractedActions.clear()

        statusMessage = "Đang giải mã tệp âm thanh ${audioFile.name} sang chuẩn 16kHz PCM..."

        workerThread = Thread {
            val pcmFile = File(context.cacheDir, "temp_auto_decode_16k.pcm")
            try {
                if (pcmFile.exists()) pcmFile.delete()

                // Bước 1: Giải mã .m4a / .mp3 / .wav sang 16kHz 16-bit Mono PCM
                val totalSeconds = decodeAudioTo16kMonoPcm(audioFile, pcmFile)
                sourceAudioDurationSec = totalSeconds
                if (totalSeconds <= 0 || !pcmFile.exists() || pcmFile.length() < 3200L) {
                    statusMessage = "Không thể giải mã luồng âm thanh từ tệp ${audioFile.name}."
                    isProcessing = false
                    return@Thread
                }

                // Bước 2: Phân tích năng lượng âm thanh (VAD) để chia các đoạn có tiếng người nói (12-18s/đoạn)
                progressPercent = 12
                statusMessage = "Đang phân tách các lượt phát biểu bằng bộ lọc VAD (${formatDuration(totalSeconds)})..."
                val chunks = splitPcmIntoVoiceChunks(pcmFile, totalSeconds)

                if (chunks.isEmpty()) {
                    statusMessage = "Tệp âm thanh không có tín hiệu giọng nói đủ lớn."
                    isProcessing = false
                    return@Thread
                }

                val langShort = when {
                    localeCode.startsWith("en") -> "EN"
                    localeCode.startsWith("de") -> "DE"
                    else -> "VI"
                }

                // Bước 3: Tự động chạy Speech-to-Text cho từng phân đoạn
                for ((idx, chunk) in chunks.withIndex()) {
                    if (cancelRequested) break

                    val pct = 15 + ((idx * 75) / chunks.size.coerceAtLeast(1))
                    progressPercent = pct.coerceIn(15, 92)
                    val timeRangeStr = "${formatDuration(chunk.startSec)} - ${formatDuration(chunk.endSec)}"
                    statusMessage =
                        "Đang tự động gỡ băng đoạn ${idx + 1}/${chunks.size} [$timeRangeStr]..."

                    val recognizedText = transcribeChunkViaPipe(pcmFile, chunk, localeCode)
                    val cleanText = recognizedText.trim()

                    if (cleanText.isNotEmpty()) {
                        val detectedLang = ExistingFileImporter.detectLanguageTag(cleanText).ifEmpty { langShort }
                        val speakerLabel = inferSpeakerLabel(idx + 1, cleanText)
                        transcribedTurns.add(
                            mapOf(
                                "speaker" to speakerLabel,
                                "lang" to detectedLang,
                                "timestamp" to timeRangeStr,
                                "content" to cleanText,
                                "translation" to ""
                            )
                        )
                    }
                }

                // Nếu thiết bị chặn luồng ống hoặc không nhận diện được chữ nào, ghi chú rõ ràng
                if (transcribedTurns.isEmpty()) {
                    transcribedTurns.add(
                        mapOf(
                            "speaker" to "Hệ thống xử lý âm thanh (${audioFile.name})",
                            "lang" to langShort,
                            "timestamp" to "00:00:00 - ${formatDuration(totalSeconds)}",
                            "content" to "Đã giải mã tệp âm thanh ${audioFile.name} (Thời lượng: ${formatDuration(totalSeconds)}). Vui lòng kiểm tra kết nối mạng hoặc quyền Google Speech Services để nhận diện văn bản tự động.",
                            "translation" to ""
                        )
                    )
                }

                // Bước 4: Tự động tổng hợp Kết luận & Bảng phân công nhiệm vụ từ nội dung đã gỡ băng
                progressPercent = 95
                statusMessage = "Đang tự động tổng hợp Kết luận, Bảng giao việc & Xuất file Word (.docx)..."
                synthesizeConclusionsAndActions(audioFile.name, totalSeconds)

                // Bước 5: Tự động xuất ngay tệp Word (.docx) chuẩn Nghị định 30/2020/NĐ-CP
                val autoJson = buildAutoMeetingJson(audioFile, totalSeconds, docLanguageMode)
                val docxResult = DocxMinutesGenerator.generateDocxFile(
                    context = context,
                    outputDir = minutesOutputDir,
                    jsonString = autoJson.toString()
                )
                autoGeneratedDocxPath = (docxResult["publicDownloadPath"] ?: docxResult["path"] ?: "").toString()

                progressPercent = 100
                statusMessage =
                    "Hoàn tất! Đã tự động gỡ băng ${transcribedTurns.size} đoạn phát biểu và tự sinh Biên bản Word (.docx) tại: $autoGeneratedDocxPath"
            } catch (e: Exception) {
                statusMessage = "Lỗi xử lý tự động: ${e.message ?: "Không xác định"}"
            } finally {
                try {
                    if (pcmFile.exists()) pcmFile.delete()
                } catch (_: Exception) {
                }
                currentPartialText = ""
                isProcessing = false
            }
        }.apply {
            priority = Thread.NORM_PRIORITY
            start()
        }
    }

    /**
     * Giải mã phần cứng (.m4a, .mp3, .aac, .wav, .ogg) về chuẩn 16,000 Hz, 16-bit Mono PCM.
     */
    private fun decodeAudioTo16kMonoPcm(inputFile: File, outPcmFile: File): Int {
        val extractor = MediaExtractor()
        try {
            extractor.setDataSource(inputFile.absolutePath)
            var audioTrackIndex = -1
            var inputFormat: MediaFormat? = null
            var mimeType = ""

            for (i in 0 until extractor.trackCount) {
                val fmt = extractor.getTrackFormat(i)
                val mime = fmt.getString(MediaFormat.KEY_MIME) ?: ""
                if (mime.startsWith("audio/")) {
                    audioTrackIndex = i
                    inputFormat = fmt
                    mimeType = mime
                    break
                }
            }

            if (audioTrackIndex < 0 || inputFormat == null) return 0
            extractor.selectTrack(audioTrackIndex)

            var inputSampleRate = if (inputFormat.containsKey(MediaFormat.KEY_SAMPLE_RATE)) {
                inputFormat.getInteger(MediaFormat.KEY_SAMPLE_RATE)
            } else 44100
            var inputChannels = if (inputFormat.containsKey(MediaFormat.KEY_CHANNEL_COUNT)) {
                inputFormat.getInteger(MediaFormat.KEY_CHANNEL_COUNT)
            } else 1

            val codec = MediaCodec.createDecoderByType(mimeType)
            codec.configure(inputFormat, null, null, 0)
            codec.start()

            val bufferInfo = MediaCodec.BufferInfo()
            var inputEOS = false
            var outputEOS = false
            var totalOutSamples16k = 0L

            FileOutputStream(outPcmFile).use { fos ->
                val outByteBuf = ByteArray(16384)
                var outBytePos = 0

                fun flushOutBuffer() {
                    if (outBytePos > 0) {
                        fos.write(outByteBuf, 0, outBytePos)
                        outBytePos = 0
                    }
                }

                var resampleAccum = 0.0
                val targetRate = 16000.0

                while (!outputEOS && !cancelRequested) {
                    if (!inputEOS) {
                        val inIndex = codec.dequeueInputBuffer(10000)
                        if (inIndex >= 0) {
                            val inBuf = codec.getInputBuffer(inIndex)
                            if (inBuf != null) {
                                val sampleSize = extractor.readSampleData(inBuf, 0)
                                if (sampleSize < 0) {
                                    codec.queueInputBuffer(
                                        inIndex,
                                        0,
                                        0,
                                        0L,
                                        MediaCodec.BUFFER_FLAG_END_OF_STREAM
                                    )
                                    inputEOS = true
                                } else {
                                    val pts = extractor.sampleTime
                                    codec.queueInputBuffer(inIndex, 0, sampleSize, pts, 0)
                                    extractor.advance()
                                }
                            }
                        }
                    }

                    val outIndex = codec.dequeueOutputBuffer(bufferInfo, 10000)
                    when {
                        outIndex >= 0 -> {
                            val outBuf = codec.getOutputBuffer(outIndex)
                            if (outBuf != null && bufferInfo.size > 0) {
                                outBuf.position(bufferInfo.offset)
                                outBuf.limit(bufferInfo.offset + bufferInfo.size)
                                outBuf.order(ByteOrder.nativeOrder())

                                val shortCount = bufferInfo.size / 2
                                val frameCount = shortCount / inputChannels.coerceAtLeast(1)
                                val step = inputSampleRate.toDouble() / targetRate

                                var frameIdx = resampleAccum
                                while (frameIdx.toInt() < frameCount) {
                                    val fInt = frameIdx.toInt()
                                    var monoSum = 0
                                    for (ch in 0 until inputChannels) {
                                        val sampleIdx = (fInt * inputChannels + ch) * 2 + bufferInfo.offset
                                        if (sampleIdx + 1 < bufferInfo.offset + bufferInfo.size) {
                                            monoSum += outBuf.getShort(sampleIdx).toInt()
                                        }
                                    }
                                    var monoSample = monoSum / inputChannels.coerceAtLeast(1)
                                    // Khuếch đại nhẹ giọng nói phòng họp để bộ nhận diện nghe rõ hơn
                                    monoSample = (monoSample * 1.8).toInt().coerceIn(-32767, 32767)

                                    if (outBytePos + 2 > outByteBuf.size) {
                                        flushOutBuffer()
                                    }
                                    outByteBuf[outBytePos++] = (monoSample and 0xFF).toByte()
                                    outByteBuf[outBytePos++] = ((monoSample shr 8) and 0xFF).toByte()
                                    totalOutSamples16k++

                                    frameIdx += step
                                }
                                resampleAccum = (frameIdx - frameCount).coerceAtLeast(0.0)
                            }
                            codec.releaseOutputBuffer(outIndex, false)
                            if ((bufferInfo.flags and MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0) {
                                outputEOS = true
                            }
                        }
                        outIndex == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED -> {
                            val newFmt = codec.outputFormat
                            if (newFmt.containsKey(MediaFormat.KEY_SAMPLE_RATE)) {
                                inputSampleRate = newFmt.getInteger(MediaFormat.KEY_SAMPLE_RATE)
                            }
                            if (newFmt.containsKey(MediaFormat.KEY_CHANNEL_COUNT)) {
                                inputChannels = newFmt.getInteger(MediaFormat.KEY_CHANNEL_COUNT)
                            }
                        }
                    }
                }
                flushOutBuffer()
            }

            try {
                codec.stop()
            } catch (_: Exception) {
            }
            try {
                codec.release()
            } catch (_: Exception) {
            }

            return (totalOutSamples16k / 16000L).toInt().coerceAtLeast(1)
        } catch (_: Exception) {
            return 0
        } finally {
            try {
                extractor.release()
            } catch (_: Exception) {
            }
        }
    }

    /**
     * Phân tách tệp 16kHz PCM thành các phân đoạn giọng nói tự nhiên dài 12 - 18 giây.
     */
    private fun splitPcmIntoVoiceChunks(pcmFile: File, totalSeconds: Int): List<SpeechChunk> {
        val bytesPerSec = 32000 // 16,000 samples * 2 bytes
        val chunks = mutableListOf<SpeechChunk>()
        val raf = RandomAccessFile(pcmFile, "r")

        try {
            val secRms = IntArray(totalSeconds)
            val buf = ByteArray(bytesPerSec)
            var maxRms = 1

            for (s in 0 until totalSeconds) {
                raf.seek(s.toLong() * bytesPerSec)
                val read = raf.read(buf)
                if (read <= 0) break
                var sumSq = 0.0
                val samples = read / 2
                var i = 0
                while (i + 1 < read) {
                    val sample = ((buf[i + 1].toInt() shl 8) or (buf[i].toInt() and 0xFF)).toShort().toInt()
                    sumSq += sample.toDouble() * sample.toDouble()
                    i += 2
                }
                val rms = sqrt(sumSq / samples.coerceAtLeast(1)).toInt()
                secRms[s] = rms
                if (rms > maxRms) maxRms = rms
            }

            val silenceThreshold = (maxRms * 0.06).toInt().coerceIn(80, 600)
            var chunkStart = -1
            var chunkIndex = 1

            for (s in 0 until totalSeconds) {
                val isVoice = secRms[s] >= silenceThreshold
                if (isVoice && chunkStart < 0) {
                    chunkStart = s
                }
                if (chunkStart >= 0) {
                    val currentLen = s - chunkStart + 1
                    val isNaturalPause = !isVoice && currentLen >= 10
                    val reachedMaxLen = currentLen >= 16

                    if (isNaturalPause || reachedMaxLen || s == totalSeconds - 1) {
                        val endSec = s + 1
                        val byteOffset = chunkStart.toLong() * bytesPerSec
                        val byteLen = ((endSec - chunkStart) * bytesPerSec)
                            .coerceAtMost((pcmFile.length() - byteOffset).toInt())
                        if (byteLen > 8000) {
                            chunks.add(
                                SpeechChunk(
                                    index = chunkIndex++,
                                    startSec = chunkStart,
                                    endSec = endSec,
                                    byteOffset = byteOffset,
                                    byteLength = byteLen
                                )
                            )
                        }
                        chunkStart = -1
                    }
                }
            }

            // Dự phòng nếu toàn bộ file có âm lượng đều nhau
            if (chunks.isEmpty() && totalSeconds > 0) {
                var s = 0
                while (s < totalSeconds) {
                    val end = (s + 15).coerceAtMost(totalSeconds)
                    val offset = s.toLong() * bytesPerSec
                    val len = ((end - s) * bytesPerSec).coerceAtMost((pcmFile.length() - offset).toInt())
                    chunks.add(SpeechChunk(chunkIndex++, s, end, offset, len))
                    s = end
                }
            }
        } finally {
            raf.close()
        }
        return chunks
    }

    /**
     * Gỡ băng 1 phân đoạn PCM bằng cách truyền qua ParcelFileDescriptor Pipe vào SpeechRecognizer (Android 13+).
     */
    private fun transcribeChunkViaPipe(
        pcmFile: File,
        chunk: SpeechChunk,
        localeCode: String
    ): String {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU) {
            return ""
        }

        val latch = CountDownLatch(1)
        var finalRecognized = ""
        var bestPartial = ""
        var recognizerRef: SpeechRecognizer? = null

        val pipe = ParcelFileDescriptor.createPipe()
        val readSide = pipe[0]
        val writeSide = pipe[1]

        // Luồng ghi dữ liệu âm thanh PCM 16kHz vào ống dẫn cho SpeechRecognizer
        val writerThread = Thread {
            try {
                ParcelFileDescriptor.AutoCloseOutputStream(writeSide).use { out ->
                    RandomAccessFile(pcmFile, "r").use { raf ->
                        raf.seek(chunk.byteOffset)
                        var remaining = chunk.byteLength
                        val block = ByteArray(6400) // 200ms ở tần số 16kHz
                        while (remaining > 0 && !cancelRequested) {
                            val toRead = remaining.coerceAtMost(block.size)
                            val read = raf.read(block, 0, toRead)
                            if (read <= 0) break
                            out.write(block, 0, read)
                            out.flush()
                            remaining -= read
                            // Giữ nhịp truyền mượt để bộ giải mã Google Speech xử lý chính xác
                            Thread.sleep(32)
                        }
                        // Ghi thêm 0.6 giây khoảng lặng cuối đoạn để kích hoạt sự kiện kết thúc câu (End of Utterance)
                        out.write(ByteArray(19200))
                        out.flush()
                    }
                }
            } catch (_: Exception) {
            }
        }
        writerThread.start()

        mainHandler.post {
            try {
                val sr = SpeechRecognizer.createSpeechRecognizer(context)
                recognizerRef = sr
                sr.setRecognitionListener(object : RecognitionListener {
                    override fun onReadyForSpeech(params: Bundle?) {}
                    override fun onBeginningOfSpeech() {}
                    override fun onRmsChanged(rmsdB: Float) {}
                    override fun onBufferReceived(buffer: ByteArray?) {}
                    override fun onEndOfSpeech() {}

                    override fun onPartialResults(partialResults: Bundle?) {
                        val list = partialResults?.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                        if (!list.isNullOrEmpty() && list[0].isNotBlank()) {
                            bestPartial = list[0].trim()
                            currentPartialText = bestPartial
                        }
                    }

                    override fun onResults(results: Bundle?) {
                        val list = results?.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                        if (!list.isNullOrEmpty() && list[0].isNotBlank()) {
                            finalRecognized = list[0].trim()
                        } else if (bestPartial.isNotBlank()) {
                            finalRecognized = bestPartial
                        }
                        latch.countDown()
                    }

                    override fun onError(error: Int) {
                        if (bestPartial.isNotBlank()) {
                            finalRecognized = bestPartial
                        }
                        latch.countDown()
                    }

                    override fun onEvent(eventType: Int, params: Bundle?) {}
                })

                val intent = android.content.Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH).apply {
                    putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
                    putExtra(RecognizerIntent.EXTRA_LANGUAGE, localeCode)
                    putExtra(RecognizerIntent.EXTRA_LANGUAGE_PREFERENCE, localeCode)
                    putExtra(RecognizerIntent.EXTRA_PARTIAL_RESULTS, true)
                    putExtra(RecognizerIntent.EXTRA_MAX_RESULTS, 1)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE, readSide)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_CHANNEL_COUNT, 1)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_ENCODING, AudioFormat.ENCODING_PCM_16BIT)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_SAMPLING_RATE, 16000)
                }
                sr.startListening(intent)
            } catch (_: Exception) {
                latch.countDown()
            }
        }

        // Chờ tối đa 22 giây cho mỗi đoạn 15 giây
        latch.await(22, TimeUnit.SECONDS)

        mainHandler.post {
            try {
                recognizerRef?.stopListening()
                recognizerRef?.destroy()
            } catch (_: Exception) {
            }
            try {
                readSide.close()
            } catch (_: Exception) {
            }
        }

        return finalRecognized.ifBlank { bestPartial }
    }

    private fun inferSpeakerLabel(turnNumber: Int, text: String): String {
        val lower = text.lowercase(Locale.getDefault())
        return when {
            lower.contains("tuyên bố") || lower.contains("khai mạc") || lower.contains("kết luận") || lower.contains("chủ trì") ->
                "Chủ trì cuộc họp (Đoạn #$turnNumber)"
            lower.contains("báo cáo") || lower.contains("trình bày") || lower.contains("kính thưa") ->
                "Báo cáo viên (Đoạn #$turnNumber)"
            else -> "Đại biểu phát biểu (Đoạn #$turnNumber)"
        }
    }

    /**
     * Tự động trích xuất Kết luận cuộc họp và Bảng phân công nhiệm vụ từ các lượt phát biểu đã gỡ băng.
     */
    private fun synthesizeConclusionsAndActions(fileName: String, durationSec: Int) {
        extractedConclusions.clear()
        extractedActions.clear()

        val conclusionKeywords = listOf(
            "thống nhất", "kết luận", "đồng ý", "phê duyệt", "chốt", "như vậy", "tóm lại",
            "yêu cầu", "đề nghị", "agree", "conclude", "decided", "approved", "beschlossen"
        )
        val actionKeywords = listOf(
            "giao", "phân công", "phụ trách", "hoàn thành", "thực hiện", "báo cáo", "nộp",
            "gửi", "trước ngày", "trong tuần", "deadline", "assign", "verantwortlich"
        )

        for (turn in transcribedTurns) {
            val content = turn["content"] ?: continue
            val ts = turn["timestamp"] ?: ""
            val lower = content.lowercase(Locale.getDefault())

            if (conclusionKeywords.any { lower.contains(it) }) {
                extractedConclusions.add("[$ts] $content")
            }
            if (actionKeywords.any { lower.contains(it) } && extractedActions.size < 8) {
                extractedActions.add(
                    mapOf(
                        "task" to content,
                        "assignee" to (turn["speaker"] ?: "Bộ phận phụ trách"),
                        "coordinator" to "Các thành viên dự họp",
                        "deadline" to "Theo tiến độ cuộc họp (Mốc $ts)"
                    )
                )
            }
        }

        if (extractedConclusions.isEmpty() && transcribedTurns.isNotEmpty()) {
            // Lấy 2 đoạn phát biểu cuối cùng làm tóm tắt kết luận cuộc họp
            val lastTurns = transcribedTurns.takeLast(2)
            for (t in lastTurns) {
                extractedConclusions.add("[Tổng hợp tại mốc ${t["timestamp"]}]: ${t["content"]}")
            }
        }

        if (extractedActions.isEmpty() && transcribedTurns.isNotEmpty()) {
            extractedActions.add(
                mapOf(
                    "task" to "Triển khai các nội dung đã thảo luận trong cuộc họp (Từ tệp ghi âm: $fileName - Thời lượng: ${formatDuration(durationSec)})",
                    "assignee" to "Các bộ phận chuyên môn",
                    "coordinator" to "Thư ký cuộc họp",
                    "deadline" to "Theo kế hoạch"
                )
            )
        }
    }

    private fun buildAutoMeetingJson(
        audioFile: File,
        durationSec: Int,
        docLanguageMode: String
    ): JSONObject {
        val baseTitle = audioFile.nameWithoutExtension
            .removePrefix("Imported_")
            .replace("_", " ")
            .trim()
        val fmtDate = SimpleDateFormat("dd/MM/yyyy", Locale.getDefault()).format(Date(audioFile.lastModified()))
        val fmtTime = SimpleDateFormat("HH 'giờ' mm 'phút' 'ngày' dd/MM/yyyy", Locale.getDefault())
            .format(Date(audioFile.lastModified()))

        val turnsJson = JSONArray()
        for (t in transcribedTurns) {
            val obj = JSONObject()
            obj.put("speaker", t["speaker"] ?: "Đại biểu")
            obj.put("lang", t["lang"] ?: "VI")
            obj.put("timestamp", t["timestamp"] ?: "")
            obj.put("content", t["content"] ?: "")
            obj.put("translation", t["translation"] ?: "")
            turnsJson.put(obj)
        }

        val concJson = JSONArray()
        for (c in extractedConclusions) {
            concJson.put(c)
        }

        val actJson = JSONArray()
        for (a in extractedActions) {
            val obj = JSONObject()
            obj.put("task", a["task"] ?: "")
            obj.put("assignee", a["assignee"] ?: "")
            obj.put("coordinator", a["coordinator"] ?: "")
            obj.put("deadline", a["deadline"] ?: "")
            actJson.put(obj)
        }

        return JSONObject().apply {
            put("docLanguageMode", docLanguageMode)
            put("governingBody", "")
            put("organizationName", "ANH'S TEAM")
            put("documentNumber", "Số: 01/2026/BB-AT")
            put("locationDate", "Ngày $fmtDate")
            put("meetingTitle", "BIÊN BẢN CUỘC HỌP")
            put("meetingSubject", "Trích xuất tự động từ tệp ghi âm: $baseTitle (Thời lượng: ${formatDuration(durationSec)})")
            put("startTime", fmtTime)
            put("endTime", "Sau ${formatDuration(durationSec)} làm việc cùng ngày")
            put("venue", "Trích xuất từ tệp ghi âm: ${audioFile.name}")
            put("chairName", "Chủ trì cuộc họp")
            put("chairTitle", "Chủ tọa")
            put("secretaryName", "Hệ thống Tự động Anh's TEAM")
            put("secretaryTitle", "Thư ký tổng hợp")
            put("attendeesList", "Các thành viên tham gia trong tệp ghi âm ${audioFile.name}")
            put("speakerTurns", turnsJson)
            put("conclusions", concJson)
            put("actionItems", actJson)
        }
    }

    private fun formatDuration(totalSec: Int): String {
        val hrs = totalSec / 3600
        val mins = (totalSec % 3600) / 60
        val secs = totalSec % 60
        return String.format(Locale.US, "%02d:%02d:%02d", hrs, mins, secs)
    }
