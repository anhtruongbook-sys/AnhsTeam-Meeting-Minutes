    fun stopProcessingEarly() {
        if (isProcessing) {
            cancelRequested = true
            statusMessage = "Đang hoàn tất phân tích giọng nói và xuất văn bản từ dữ liệu đã gỡ băng..."
        }
    }

    fun startAutoProcessAudioFile(
        audioFile: File,
        localeCode: String,
        docLanguageMode: String,
        minutesOutputDir: File
    ) {
        if (isProcessing) return
        isProcessing = true
        cancelRequested = false
        progressPercent = 2
        sourceAudioName = audioFile.name
        autoGeneratedDocxPath = ""
        currentPartialText = ""
        detectedSpeakerCount = 1
        detectedDocumentType = "MONOLOGUE"
        diarizationReport = ""
        transcribedTurns.clear()
        extractedConclusions.clear()
        extractedActions.clear()

        statusMessage = "Đang giải mã nhanh tệp âm thanh ${audioFile.name} sang chuẩn 16kHz PCM..."

        workerThread = Thread {
            val pcmFile = File(context.cacheDir, "temp_auto_decode_16k.pcm")
            try {
                if (pcmFile.exists()) pcmFile.delete()

                val langShort = when {
                    localeCode.startsWith("en") -> "EN"
                    localeCode.startsWith("de") -> "DE"
                    else -> "VI"
                }

                // Bước 1: Giải mã .m4a / .mp3 / .wav sang 16kHz 16-bit Mono PCM
                var totalSeconds = decodeAudioTo16kMonoPcm(audioFile, pcmFile)
                if (totalSeconds <= 0 && pcmFile.exists() && pcmFile.length() >= 3200L) {
                    totalSeconds = (pcmFile.length() / 32000L).toInt().coerceAtLeast(1)
                }
                if (totalSeconds <= 0) {
                    totalSeconds = extractWavOrRawFallback(audioFile, pcmFile)
                }

                val metaDurationSec = queryDurationWithRetriever(audioFile)
                if (totalSeconds <= 0 && metaDurationSec > 0) {
                    totalSeconds = metaDurationSec
                }
                sourceAudioDurationSec = totalSeconds.coerceAtLeast(1)

                var clusters = listOf<SpeakerCluster>()

                // Bước 2: Phân tích VAD + Phân biệt Giọng nói Âm học (Speaker Diarization)
                if (pcmFile.exists() && pcmFile.length() >= 3200L) {
                    val actualPcmSec = (pcmFile.length() / 32000L).toInt().coerceAtLeast(1)
                    sourceAudioDurationSec = actualPcmSec.coerceAtLeast(metaDurationSec)

                    progressPercent = 14
                    statusMessage =
                        "Đang phân tích phổ giọng nói (Pitch F0 & Âm sắc) để đếm số người nói và tách lượt..."
                    val chunks = splitPcmAndAnalyzeVoices(pcmFile, actualPcmSec)
                    clusters = clusterSpeakersAcrossChunks(chunks)
                    detectedSpeakerCount = clusters.size.coerceAtLeast(1)

                    val speakerSummaryParts = clusters.map { c ->
                        "Giọng #${c.id}: ${c.voiceProfileLabel()} (${c.chunkCount} đoạn)"
                    }
                    diarizationReport = if (detectedSpeakerCount == 1) {
                        val c0 = clusters.firstOrNull()
                        val desc = c0?.voiceProfileLabel() ?: "Giọng đơn nhất"
                        "PHÁT HIỆN CHỈ 01 NGƯỜI NÓI ($desc) -> Nội dung Độc thoại / Ghi chú âm thanh (Không phải Biên bản cuộc họp nhiều người)."
                    } else {
                        "PHÁT HIỆN $detectedSpeakerCount GIỌNG NÓI KHÁC NHAU (${speakerSummaryParts.joinToString("; ")}) -> Nội dung Cuộc họp / Hội thoại nhiều người."
                    }

                    // Bước 3: Tự động chạy Speech-to-Text cho từng phân đoạn
                    for ((idx, chunk) in chunks.withIndex()) {
                        if (cancelRequested) break

                        val pct = 18 + ((idx * 74) / chunks.size.coerceAtLeast(1))
                        progressPercent = pct.coerceIn(18, 92)
                        val timeRangeStr = "${formatDuration(chunk.startSec)} - ${formatDuration(chunk.endSec)}"
                        val spkTag = if (detectedSpeakerCount == 1) {
                            "01 Người nói (${chunk.speakerVoiceDesc})"
                        } else {
                            "Người nói #${chunk.speakerClusterId} (${chunk.speakerVoiceDesc})"
                        }
                        statusMessage =
                            "[$spkTag] Đang gỡ băng đoạn ${idx + 1}/${chunks.size} [$timeRangeStr]..."

                        val recognizedText = transcribeChunkViaPipe(pcmFile, chunk, localeCode)
                        val cleanText = recognizedText.trim()

                        if (cleanText.isNotEmpty()) {
                            val detectedLang =
                                ExistingFileImporter.detectLanguageTag(cleanText).ifEmpty { langShort }
                            val speakerLabel = if (detectedSpeakerCount == 1) {
                                "Người nói duy nhất (${chunk.speakerVoiceDesc})"
                            } else {
                                "Người nói #${chunk.speakerClusterId} (${chunk.speakerVoiceDesc})"
                            }
                            transcribedTurns.add(
                                mapOf(
                                    "speaker" to speakerLabel,
                                    "speakerClusterId" to chunk.speakerClusterId.toString(),
                                    "lang" to detectedLang,
                                    "timestamp" to timeRangeStr,
                                    "content" to cleanText,
                                    "translation" to ""
                                )
                            )
                        }
                    }
                }

                // Quyết định loại tài liệu: MONOLOGUE (Bản gỡ băng 1 người nói) hay MEETING (Biên bản cuộc họp nhiều người)
                detectedDocumentType = determineDocumentType(detectedSpeakerCount, transcribedTurns)
                if (detectedDocumentType == "MONOLOGUE" && diarizationReport.isEmpty()) {
                    diarizationReport =
                        "PHÁT HIỆN CHỈ 01 NGƯỜI NÓI -> Nội dung Độc thoại / Bản ghi âm cá nhân (Không phải Biên bản họp)."
                }

                if (transcribedTurns.isEmpty()) {
                    val durLabel = formatDuration(sourceAudioDurationSec)
                    val spkHeader = if (detectedSpeakerCount == 1) {
                        val c0 = clusters.firstOrNull()?.voiceProfileLabel() ?: "01 Giọng nói"
                        "Người nói duy nhất ($c0)"
                    } else {
                        "Hệ thống phân tích âm thanh ($detectedSpeakerCount giọng nói)"
                    }
                    transcribedTurns.add(
                        mapOf(
                            "speaker" to spkHeader,
                            "speakerClusterId" to "1",
                            "lang" to langShort,
                            "timestamp" to "00:00:00 - $durLabel",
                            "content" to "Đã giải mã và phân tích phổ giọng nói tệp ${audioFile.name} (Thời lượng: $durLabel). Kết quả: $diarizationReport (Lưu ý: Bộ nhận diện giọng nói Google Speech trên máy chưa trả về văn bản cho đoạn âm thanh này; vui lòng kiểm tra kết nối mạng hoặc âm lượng giọng nói trong tệp).",
                            "translation" to ""
                        )
                    )
                }

                // Bước 4: Tổng hợp Tóm tắt (cho Độc thoại 1 người) hoặc Kết luận & Bảng giao việc (cho Biên bản họp nhiều người)
                progressPercent = 95
                statusMessage = if (detectedDocumentType == "MONOLOGUE") {
                    "Phát hiện chỉ 01 người nói (Không phải cuộc họp). Đang xuất Bản Gỡ Băng & Tóm Tắt Ghi Âm (.docx)..."
                } else {
                    "Phát hiện $detectedSpeakerCount người nói. Đang tổng hợp Kết luận, Bảng giao việc & Xuất Biên Bản Họp (.docx)..."
                }
                synthesizeConclusionsAndActions(audioFile.name, sourceAudioDurationSec)

                // Bước 5: Tự động xuất ngay tệp Word (.docx) theo đúng loại (Độc thoại 1 người vs Biên bản họp nhiều người)
                val autoJson = buildAutoMeetingJson(audioFile, sourceAudioDurationSec, docLanguageMode)
                val docxResult = DocxMinutesGenerator.generateDocxFile(
                    context = context,
                    outputDir = minutesOutputDir,
                    jsonString = autoJson.toString()
                )
                autoGeneratedDocxPath = (docxResult["path"] ?: "").toString()
                val publicDisplayPath =
                    (docxResult["publicDownloadPath"] ?: docxResult["path"] ?: "").toString()

                progressPercent = 100
                val docTypeLabel = if (detectedDocumentType == "MONOLOGUE") {
                    "BẢN GỠ BĂNG ĐỘC THOẠI (01 NGƯỜI NÓI - KHÔNG PHẢI BIÊN BẢN HỌP)"
                } else {
                    "BIÊN BẢN CUỘC HỌP ($detectedSpeakerCount GIỌNG NÓI KHÁC NHAU)"
                }
                statusMessage =
                    "Hoàn tất! Phân loại: $docTypeLabel • Đã xuất file Word (.docx) tại: $publicDisplayPath"
            } catch (e: Exception) {
                statusMessage = "Đã hoàn tất xử lý với ghi chú: ${e.message ?: "Kiểm tra định dạng tệp"}"
            } finally {
                try {
                    if (pcmFile.exists()) pcmFile.delete()
                } catch (_: Exception) {
                }
                currentPartialText = ""
                isProcessing = false
            }
        }.apply {
            priority = Thread.NORM_PRIORITY
            start()
        }
    }

    /**
     * Phân loại tự động:
     * - Nếu chỉ có 1 giọng nói âm học (detectedSpeakerCount == 1) và nội dung không có các từ khóa điều hành cuộc họp nhiều bên -> "MONOLOGUE" (Không phải biên bản họp).
     * - Nếu có từ 2 giọng nói khác nhau trở lên (detectedSpeakerCount >= 2) -> "MEETING" (Biên bản cuộc họp).
     */
    private fun determineDocumentType(
        speakerCount: Int,
        turns: List<Map<String, String>>
    ): String {
        if (speakerCount >= 2) {
            return "MEETING"
        }
        val allText = turns.joinToString(" ") { it["content"] ?: "" }.lowercase(Locale.getDefault())
        val explicitMultiPartyKeywords = listOf(
            "biên bản cuộc họp", "tuyên bố lý do", "chủ trì cuộc họp", "thư ký cuộc họp",
            "mời anh", "mời chị", "ý kiến của", "thống nhất giao", "phân công nhiệm vụ"
        )
        val matchCount = explicitMultiPartyKeywords.count { allText.contains(it) }
        return if (matchCount >= 2) "MEETING" else "MONOLOGUE"
    }

    /**
     * Phân tách tệp 16kHz PCM thành các đoạn thoại (6 - 12 giây) và đo đặc trưng sinh trắc giọng nói (F0, ZCR, Spectral Brightness).
     */
    private fun splitPcmAndAnalyzeVoices(pcmFile: File, totalSeconds: Int): List<SpeechChunk> {
        val bytesPerSec = 32000 // 16,000 samples * 2 bytes
        val chunks = mutableListOf<SpeechChunk>()
        val raf = RandomAccessFile(pcmFile, "r")

        try {
            val secRms = IntArray(totalSeconds)
            val buf = ByteArray(bytesPerSec)
            var maxRms = 1

            for (s in 0 until totalSeconds) {
                raf.seek(s.toLong() * bytesPerSec)
                val read = raf.read(buf)
                if (read <= 0) break
                var sumSq = 0.0
                val samples = read / 2
                var i = 0
                while (i + 1 < read) {
                    val sample =
                        ((buf[i + 1].toInt() shl 8) or (buf[i].toInt() and 0xFF)).toShort().toInt()
                    sumSq += sample.toDouble() * sample.toDouble()
                    i += 2
                }
                val rms = sqrt(sumSq / samples.coerceAtLeast(1)).toInt()
                secRms[s] = rms
                if (rms > maxRms) maxRms = rms
            }

            val silenceThreshold = (maxRms * 0.06).toInt().coerceIn(80, 600)
            var chunkStart = -1
            var chunkIndex = 1

            for (s in 0 until totalSeconds) {
                val isVoice = secRms[s] >= silenceThreshold
                if (isVoice && chunkStart < 0) {
                    chunkStart = s
                }
                if (chunkStart >= 0) {
                    val currentLen = s - chunkStart + 1
                    // Tách đoạn ở khoảng nghỉ >= 6 giây để bắt kịp sự thay đổi người nói trong cuộc họp
                    val isNaturalPause = !isVoice && currentLen >= 6
                    val reachedMaxLen = currentLen >= 12

                    if (isNaturalPause || reachedMaxLen || s == totalSeconds - 1) {
                        val endSec = s + 1
                        val byteOffset = chunkStart.toLong() * bytesPerSec
                        val byteLen = ((endSec - chunkStart) * bytesPerSec)
                            .coerceAtMost((pcmFile.length() - byteOffset).toInt())
                        if (byteLen > 6400) {
                            val sig = computeVoiceSignature(raf, byteOffset, byteLen)
                            chunks.add(
                                SpeechChunk(
                                    index = chunkIndex++,
                                    startSec = chunkStart,
                                    endSec = endSec,
                                    byteOffset = byteOffset,
                                    byteLength = byteLen,
                                    signature = sig
                                )
                            )
                        }
                        chunkStart = -1
                    }
                }
            }

            if (chunks.isEmpty() && totalSeconds > 0) {
                var s = 0
                while (s < totalSeconds) {
                    val end = (s + 10).coerceAtMost(totalSeconds)
                    val offset = s.toLong() * bytesPerSec
                    val len =
                        ((end - s) * bytesPerSec).coerceAtMost((pcmFile.length() - offset).toInt())
                    if (len > 3200) {
                        val sig = computeVoiceSignature(raf, offset, len)
                        chunks.add(SpeechChunk(chunkIndex++, s, end, offset, len, sig))
                    }
                    s = end
                }
            }
        } finally {
            raf.close()
        }
        return chunks
    }

    /**
     * Tính toán đặc trưng sinh trắc giọng nói (Voice Signature) từ mẫu PCM 16kHz:
     * - Tần số cơ bản F0 (Hz) bằng thuật toán Tự tương quan chuẩn hóa (Normalized Autocorrelation) trong dải giọng người [75Hz - 340Hz].
     * - Độ sáng âm sắc (Spectral Brightness / Formant High-Frequency Energy Ratio).
     * - Tốc độ qua điểm không (Zero-Crossing Rate Hz).
     */
    private fun computeVoiceSignature(
        raf: RandomAccessFile,
        byteOffset: Long,
        byteLength: Int
    ): VoiceSignature {
        val raw = ByteArray(byteLength)
        raf.seek(byteOffset)
        val totalRead = raf.read(raw)
        if (totalRead < 1600) {
            return VoiceSignature(140.0, 900.0, 0.35, 200, 0.5)
        }

        val sampleCount = totalRead / 2
        val samples = ShortArray(sampleCount)
        var sumSqAll = 0.0
        for (i in 0 until sampleCount) {
            val lo = raw[i * 2].toInt() and 0xFF
            val hi = raw[i * 2 + 1].toInt() shl 8
            val s = (hi or lo).toShort()
            samples[i] = s
            sumSqAll += s.toDouble() * s.toDouble()
        }
        val overallRms = sqrt(sumSqAll / sampleCount.coerceAtLeast(1)).toInt()
        val voicedGate = (overallRms * 0.45).toInt().coerceAtLeast(120)

        val frameSize = 480 // 30ms ở 16,000 Hz
        val frameStep = 320 // Bước nhảy 20ms
        val minLag = 47     // ~340 Hz
        val maxLag = 213    // ~75 Hz

        val pitchList = mutableListOf<Double>()
        val zcrList = mutableListOf<Double>()
        val brightnessList = mutableListOf<Double>()
        var totalFrames = 0
        var voicedFrames = 0

        var start = 0
        while (start + frameSize <= sampleCount) {
            totalFrames++
            var e0 = 0.0
            var diffSq = 0.0
            var zeroCrossings = 0
            for (n in 0 until frameSize) {
                val cur = samples[start + n].toDouble()
                e0 += cur * cur
                if (n > 0) {
                    val prev = samples[start + n - 1].toDouble()
                    val d = cur - prev
                    diffSq += d * d
                    if ((cur >= 0 && prev < 0) || (cur < 0 && prev >= 0)) {
                        zeroCrossings++
                    }
                }
            }
            val frameRms = sqrt(e0 / frameSize)
            val zcrHz = (zeroCrossings * 16000.0) / (2.0 * frameSize)

            // Chỉ phân tích F0 trên các khung nguyên âm hữu thanh (Voiced Vowel Frames)
            if (frameRms >= voicedGate && zcrHz < 2800.0 && e0 > 1.0) {
                var bestLag = -1
                var bestCorr = 0.0
                for (lag in minLag..maxLag step 2) {
                    var sumProd = 0.0
                    var eLag = 0.0
                    val limit = frameSize - lag
                    var k = 0
                    while (k < limit) {
                        val a = samples[start + k].toDouble()
                        val b = samples[start + k + lag].toDouble()
                        sumProd += a * b
                        eLag += b * b
                        k += 2 // Tăng tốc 2x
                    }
                    val denom = sqrt((e0 * 0.5) * eLag)
                    if (denom > 1.0) {
                        val normCorr = sumProd / denom
                        if (normCorr > bestCorr) {
                            bestCorr = normCorr
                            bestLag = lag
                        }
                    }
                }

                if (bestLag > 0 && bestCorr >= 0.28) {
                    voicedFrames++
                    val f0 = 16000.0 / bestLag.toDouble()
                    if (f0 in 75.0..340.0) {
                        pitchList.add(f0)
                        zcrList.add(zcrHz)
                        brightnessList.add(sqrt(diffSq / e0))
                    }
                }
            }
            start += frameStep
        }

        val medianPitch = if (pitchList.isNotEmpty()) {
            pitchList.sorted()[pitchList.size / 2]
        } else 140.0

        val medianZcr = if (zcrList.isNotEmpty()) {
            zcrList.sorted()[zcrList.size / 2]
        } else 950.0

        val medianBrightness = if (brightnessList.isNotEmpty()) {
            brightnessList.sorted()[brightnessList.size / 2]
        } else 0.36

        val voicedRatio = if (totalFrames > 0) voicedFrames.toDouble() / totalFrames else 0.5

        return VoiceSignature(
            pitchHz = medianPitch,
            zcrHz = medianZcr,
            spectralBrightness = medianBrightness,
            rmsEnergy = overallRms,
            voicedRatio = voicedRatio
        )
    }

    /**
     * Phân cụm các đoạn giọng nói thành các Người nói khác nhau (Speaker Clustering):
     * - Tính khoảng cách Semitone về cao độ F0 + Độ lệch âm sắc thanh quản (Spectral Brightness).
     * - Nếu toàn bộ các đoạn có giọng nói đồng nhất (khoảng cách < ngưỡng sinh trắc), kết luận CHỈ CÓ 01 NGƯỜI NÓI.
     * - Nếu có >= 2 cụm giọng rõ rệt (mỗi cụm xuất hiện đủ thời lượng hoặc cách biệt rõ rệt về cao độ/âm sắc), phân biệt Người nói #1, #2, #3...
     */
    private fun clusterSpeakersAcrossChunks(chunks: List<SpeechChunk>): List<SpeakerCluster> {
        if (chunks.isEmpty()) return emptyList()

        val rawClusters = mutableListOf<SpeakerCluster>()

        fun voiceDistance(sig: VoiceSignature, cluster: SpeakerCluster): Double {
            val ratio = (sig.pitchHz / cluster.meanPitchHz).coerceIn(0.25, 4.0)
            val semitoneDiff = 12.0 * (abs(ln(ratio)) / ln(2.0))
            val brightnessDiff = abs(sig.spectralBrightness - cluster.meanBrightness) * 15.0
            val zcrDiff = abs(sig.zcrHz - cluster.meanZcrHz) * 0.002
            return semitoneDiff + brightnessDiff + zcrDiff
        }

        // Ngưỡng phân tách 2 người nói khác nhau (~3.5 bán âm + độ lệch âm sắc)
        val newSpeakerThreshold = 3.65

        for (chunk in chunks) {
            val sig = chunk.signature
            var bestCluster: SpeakerCluster? = null
            var minDist = Double.MAX_VALUE

            for (c in rawClusters) {
                val d = voiceDistance(sig, c)
                if (d < minDist) {
                    minDist = d
                    bestCluster = c
                }
            }

            if (bestCluster == null || (minDist > newSpeakerThreshold && rawClusters.size < 5)) {
                val newId = rawClusters.size + 1
                val created = SpeakerCluster(
                    id = newId,
                    meanPitchHz = sig.pitchHz,
                    meanBrightness = sig.spectralBrightness,
                    meanZcrHz = sig.zcrHz,
                    chunkCount = 1,
                    totalDurationSec = (chunk.endSec - chunk.startSec).coerceAtLeast(1)
                )
                rawClusters.add(created)
                chunk.speakerClusterId = newId
            } else {
                val n = bestCluster.chunkCount
                bestCluster.meanPitchHz = (bestCluster.meanPitchHz * n + sig.pitchHz) / (n + 1)
                bestCluster.meanBrightness =
                    (bestCluster.meanBrightness * n + sig.spectralBrightness) / (n + 1)
                bestCluster.meanZcrHz = (bestCluster.meanZcrHz * n + sig.zcrHz) / (n + 1)
                bestCluster.chunkCount = n + 1
                bestCluster.totalDurationSec += (chunk.endSec - chunk.startSec).coerceAtLeast(1)
                chunk.speakerClusterId = bestCluster.id
            }
        }

        // Hậu xử lý chống nhiễu: Nếu một cụm phụ chỉ có 1 đoạn ngắn và cách cụm chính không quá xa (< 4.8),
        // gộp vào cụm chính để tránh việc 1 người nói nhấn giọng bị tách nhầm thành 2 người.
        if (rawClusters.size > 1 && chunks.size >= 3) {
            val dominant = rawClusters.maxByOrNull { it.chunkCount }!!
            val validClusters = mutableListOf<SpeakerCluster>()

            for (c in rawClusters) {
                if (c.id == dominant.id) {
                    validClusters.add(c)
                } else {
                    val ratio = (c.meanPitchHz / dominant.meanPitchHz).coerceIn(0.25, 4.0)
                    val semi = 12.0 * (abs(ln(ratio)) / ln(2.0))
                    val bDiff = abs(c.meanBrightness - dominant.meanBrightness) * 15.0
                    val distToDom = semi + bDiff

                    val isOutlierSingleChunk = c.chunkCount == 1 && distToDom < 4.8
                    if (isOutlierSingleChunk) {
                        // Gộp vào người nói chính
                        for (ch in chunks) {
                            if (ch.speakerClusterId == c.id) {
                                ch.speakerClusterId = dominant.id
                            }
                        }
                        dominant.chunkCount += c.chunkCount
                        dominant.totalDurationSec += c.totalDurationSec
                    } else {
                        validClusters.add(c)
                    }
                }
            }

            // Đánh số lại thứ tự Người nói #1, #2, #3...
            val idMap = mutableMapOf<Int, SpeakerCluster>()
            validClusters.forEachIndexed { idx, cluster ->
                val newId = idx + 1
                val remapped = cluster.copy(id = newId)
                idMap[cluster.id] = remapped
            }
            for (ch in chunks) {
                val mapped = idMap[ch.speakerClusterId] ?: idMap.values.first()
                ch.speakerClusterId = mapped.id
                ch.speakerVoiceDesc = mapped.voiceProfileLabel()
            }
            return idMap.values.toList()
        }

        for (ch in chunks) {
            val c = rawClusters.find { it.id == ch.speakerClusterId } ?: rawClusters.first()
            ch.speakerVoiceDesc = c.voiceProfileLabel()
        }
        return rawClusters
    }

    private fun queryDurationWithRetriever(file: File): Int {
