        }
    }

    /**
     * Giải mã phần cứng tốc độ cao (.m4a, .mp3, .aac, .wav, .ogg, .3gp, .amr) về chuẩn 16,000 Hz, 16-bit Mono PCM.
     */
    private fun decodeAudioTo16kMonoPcm(inputFile: File, outPcmFile: File): Int {
        val extractor = MediaExtractor()
        var codec: MediaCodec? = null
        var totalOutSamples16k = 0L

        try {
            var dataSourceSet = false
            try {
                FileInputStream(inputFile).use { fis ->
                    extractor.setDataSource(fis.fd)
                    dataSourceSet = true
                }
            } catch (_: Exception) {
            }
            if (!dataSourceSet) {
                extractor.setDataSource(inputFile.absolutePath)
            }

            var audioTrackIndex = -1
            var inputFormat: MediaFormat? = null
            var mimeType = ""

            for (i in 0 until extractor.trackCount) {
                val fmt = extractor.getTrackFormat(i)
                val mime = fmt.getString(MediaFormat.KEY_MIME) ?: ""
                if (mime.startsWith("audio/")) {
                    audioTrackIndex = i
                    inputFormat = fmt
                    mimeType = mime
                    break
                }
            }

            if (audioTrackIndex < 0 || inputFormat == null) return 0
            extractor.selectTrack(audioTrackIndex)

            var inputSampleRate = try {
                if (inputFormat.containsKey(MediaFormat.KEY_SAMPLE_RATE)) {
                    inputFormat.getInteger(MediaFormat.KEY_SAMPLE_RATE)
                } else 44100
            } catch (_: Exception) {
                44100
            }.coerceAtLeast(8000)

            var inputChannels = try {
                if (inputFormat.containsKey(MediaFormat.KEY_CHANNEL_COUNT)) {
                    inputFormat.getInteger(MediaFormat.KEY_CHANNEL_COUNT)
                } else 1
            } catch (_: Exception) {
                1
            }.coerceAtLeast(1)

            val totalDurationUs = try {
                if (inputFormat.containsKey(MediaFormat.KEY_DURATION)) {
                    inputFormat.getLong(MediaFormat.KEY_DURATION)
                } else 0L
            } catch (_: Exception) {
                0L
            }

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N) {
                try {
                    inputFormat.setInteger(MediaFormat.KEY_PCM_ENCODING, AudioFormat.ENCODING_PCM_16BIT)
                } catch (_: Exception) {
                }
            }

            codec = try {
                val c = MediaCodec.createDecoderByType(mimeType)
                c.configure(inputFormat, null, null, 0)
                c
            } catch (_: Exception) {
                val codecName =
                    MediaCodecList(MediaCodecList.ALL_CODECS).findDecoderForFormat(inputFormat)
                        ?: return 0
                val c = MediaCodec.createByCodecName(codecName)
                c.configure(inputFormat, null, null, 0)
                c
            }

            codec.start()

            val bufferInfo = MediaCodec.BufferInfo()
            var inputEOS = false
            var outputEOS = false
            var lastPtsUs = 0L
            var consecutiveTryAgainAfterInputEOS = 0
            var outputPcmEncoding = AudioFormat.ENCODING_PCM_16BIT
            var lastProgressUpdateMs = System.currentTimeMillis()
            val maxSamples16k = 1500L * 16000L

            FileOutputStream(outPcmFile).use { fos ->
                val outByteBuf = ByteArray(32768)
                var outBytePos = 0
                var rawFrameBytes = ByteArray(65536)

                fun flushOutBuffer() {
                    if (outBytePos > 0) {
                        fos.write(outByteBuf, 0, outBytePos)
                        outBytePos = 0
                    }
                }

                var resampleAccum = 0.0
                val targetRate = 16000.0

                while (!outputEOS && !cancelRequested && totalOutSamples16k < maxSamples16k) {
                    if (!inputEOS) {
                        try {
                            val inIndex = codec.dequeueInputBuffer(5000)
                            if (inIndex >= 0) {
                                val inBuf = codec.getInputBuffer(inIndex)
                                if (inBuf != null) {
                                    inBuf.clear()
                                    val sampleSize = extractor.readSampleData(inBuf, 0)
                                    if (sampleSize < 0) {
                                        codec.queueInputBuffer(
                                            inIndex,
                                            0,
                                            0,
                                            lastPtsUs + 1000L,
                                            MediaCodec.BUFFER_FLAG_END_OF_STREAM
                                        )
                                        inputEOS = true
                                    } else {
                                        val pts = extractor.sampleTime.coerceAtLeast(0L)
                                        lastPtsUs = pts
                                        codec.queueInputBuffer(inIndex, 0, sampleSize, pts, 0)
                                        extractor.advance()
                                    }
                                }
                            }
                        } catch (_: Exception) {
                            inputEOS = true
                        }
                    }

                    try {
                        val outIndex = codec.dequeueOutputBuffer(bufferInfo, 5000)
                        when {
                            outIndex >= 0 -> {
                                consecutiveTryAgainAfterInputEOS = 0
                                val outBuf = codec.getOutputBuffer(outIndex)
                                val isConfig =
                                    (bufferInfo.flags and MediaCodec.BUFFER_FLAG_CODEC_CONFIG) != 0

                                if (outBuf != null && bufferInfo.size > 0 && !isConfig) {
                                    val avail = outBuf.remaining().coerceAtMost(bufferInfo.size)
                                    if (avail > 0) {
                                        if (rawFrameBytes.size < avail) {
                                            rawFrameBytes = ByteArray(avail)
                                        }
                                        outBuf.get(rawFrameBytes, 0, avail)

                                        val step =
                                            (inputSampleRate.toDouble() / targetRate).coerceAtLeast(0.25)

                                        if (outputPcmEncoding == AudioFormat.ENCODING_PCM_FLOAT) {
                                            val floatCount = avail / 4
                                            val frameCount =
                                                floatCount / inputChannels.coerceAtLeast(1)
                                            val fb = ByteBuffer.wrap(rawFrameBytes, 0, avail)
                                                .order(ByteOrder.LITTLE_ENDIAN)
                                                .asFloatBuffer()
                                            var frameIdx = resampleAccum
                                            while (frameIdx.toInt() < frameCount) {
                                                val fInt = frameIdx.toInt()
                                                var monoSum = 0f
                                                for (ch in 0 until inputChannels) {
                                                    val idx = fInt * inputChannels + ch
                                                    if (idx < floatCount) {
                                                        monoSum += fb.get(idx)
                                                    }
                                                }
                                                val monoFloat =
                                                    (monoSum / inputChannels.coerceAtLeast(1)) * 1.6f
                                                val monoSample = (monoFloat * 32767f).toInt()
                                                    .coerceIn(-32767, 32767)

                                                if (outBytePos + 2 > outByteBuf.size) {
                                                    flushOutBuffer()
                                                }
                                                outByteBuf[outBytePos++] =
                                                    (monoSample and 0xFF).toByte()
                                                outByteBuf[outBytePos++] =
                                                    ((monoSample shr 8) and 0xFF).toByte()
                                                totalOutSamples16k++
                                                frameIdx += step
                                            }
                                            resampleAccum =
                                                (frameIdx - frameCount).coerceAtLeast(0.0)
                                        } else {
                                            val shortCount = avail / 2
                                            val frameCount =
                                                shortCount / inputChannels.coerceAtLeast(1)
                                            var frameIdx = resampleAccum
                                            while (frameIdx.toInt() < frameCount) {
                                                val fInt = frameIdx.toInt()
                                                var monoSum = 0
                                                for (ch in 0 until inputChannels) {
                                                    val byteIdx = (fInt * inputChannels + ch) * 2
                                                    if (byteIdx + 1 < avail) {
                                                        val lo =
                                                            rawFrameBytes[byteIdx].toInt() and 0xFF
                                                        val hi =
                                                            rawFrameBytes[byteIdx + 1].toInt() shl 8
                                                        monoSum += (hi or lo).toShort().toInt()
                                                    }
                                                }
                                                var monoSample =
                                                    monoSum / inputChannels.coerceAtLeast(1)
                                                monoSample = (monoSample * 1.6).toInt()
                                                    .coerceIn(-32767, 32767)

                                                if (outBytePos + 2 > outByteBuf.size) {
                                                    flushOutBuffer()
                                                }
                                                outByteBuf[outBytePos++] =
                                                    (monoSample and 0xFF).toByte()
                                                outByteBuf[outBytePos++] =
                                                    ((monoSample shr 8) and 0xFF).toByte()
                                                totalOutSamples16k++
                                                frameIdx += step
                                            }
                                            resampleAccum =
                                                (frameIdx - frameCount).coerceAtLeast(0.0)
                                        }
                                    }
                                }

                                codec.releaseOutputBuffer(outIndex, false)
                                if ((bufferInfo.flags and MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0) {
                                    outputEOS = true
                                }

                                val now = System.currentTimeMillis()
                                if (now - lastProgressUpdateMs > 250) {
                                    lastProgressUpdateMs = now
                                    val decodedSecSoFar = (totalOutSamples16k / 16000L).toInt()
                                    if (totalDurationUs > 0) {
                                        val ratio = (lastPtsUs.toDouble() / totalDurationUs.toDouble()).coerceIn(0.0, 1.0)
                                        progressPercent = (2 + (ratio * 11).toInt()).coerceIn(2, 13)
                                    }
                                    statusMessage =
                                        "Đang giải mã âm thanh ${inputFile.name}: đã đọc ${formatDuration(decodedSecSoFar)}..."
                                }
                            }
                            outIndex == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED -> {
                                val newFmt = codec.outputFormat
                                if (newFmt.containsKey(MediaFormat.KEY_SAMPLE_RATE)) {
                                    inputSampleRate =
                                        newFmt.getInteger(MediaFormat.KEY_SAMPLE_RATE).coerceAtLeast(8000)
                                }
                                if (newFmt.containsKey(MediaFormat.KEY_CHANNEL_COUNT)) {
                                    inputChannels =
                                        newFmt.getInteger(MediaFormat.KEY_CHANNEL_COUNT).coerceAtLeast(1)
                                }
                                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N &&
                                    newFmt.containsKey(MediaFormat.KEY_PCM_ENCODING)
                                ) {
                                    outputPcmEncoding = newFmt.getInteger(MediaFormat.KEY_PCM_ENCODING)
                                }
                            }
                            outIndex == MediaCodec.INFO_TRY_AGAIN_LATER -> {
                                if (inputEOS) {
                                    consecutiveTryAgainAfterInputEOS++
                                    if (consecutiveTryAgainAfterInputEOS >= 15) {
                                        outputEOS = true
                                    }
                                }
                            }
                        }
                    } catch (_: Exception) {
                        outputEOS = true
                    }
                }
                flushOutBuffer()
            }
        } catch (_: Exception) {
        } finally {
            try {
                codec?.stop()
            } catch (_: Exception) {
            }
            try {
                codec?.release()
            } catch (_: Exception) {
            }
            try {
                extractor.release()
            } catch (_: Exception) {
            }
        }

        val finalBytes = if (outPcmFile.exists()) outPcmFile.length() else 0L
        return if (finalBytes >= 3200L) {
            (finalBytes / 32000L).toInt().coerceAtLeast(1)
        } else {
            0
        }
    }

    private fun extractWavOrRawFallback(inputFile: File, outPcmFile: File): Int {
        if (!inputFile.name.endsWith(".wav", ignoreCase = true)) return 0
        return try {
            FileInputStream(inputFile).use { fis ->
                FileOutputStream(outPcmFile).use { fos ->
                    val header = ByteArray(44)
                    if (fis.read(header) == 44) {
                        fis.copyTo(fos)
                    }
                }
            }
            if (outPcmFile.exists() && outPcmFile.length() >= 3200L) {
                (outPcmFile.length() / 32000L).toInt().coerceAtLeast(1)
            } else 0
        } catch (_: Exception) {
            0
        }
    }

    /**
     * Gỡ băng 1 phân đoạn PCM bằng cách truyền qua ParcelFileDescriptor Pipe vào SpeechRecognizer (Android 13+).
     */
    private fun transcribeChunkViaPipe(
        pcmFile: File,
        chunk: SpeechChunk,
        localeCode: String
    ): String {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU) {
            return ""
        }

        val latch = CountDownLatch(1)
        var finalRecognized = ""
        var bestPartial = ""
        var recognizerRef: SpeechRecognizer? = null

        val pipe = ParcelFileDescriptor.createPipe()
        val readSide = pipe[0]
        val writeSide = pipe[1]

        mainHandler.post {
            try {
                val sr = SpeechRecognizer.createSpeechRecognizer(context)
                recognizerRef = sr
                sr.setRecognitionListener(object : RecognitionListener {
                    override fun onReadyForSpeech(params: Bundle?) {}
                    override fun onBeginningOfSpeech() {}
                    override fun onRmsChanged(rmsdB: Float) {}
                    override fun onBufferReceived(buffer: ByteArray?) {}
                    override fun onEndOfSpeech() {}

                    override fun onPartialResults(partialResults: Bundle?) {
                        val list =
                            partialResults?.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                        if (!list.isNullOrEmpty() && list[0].isNotBlank()) {
                            bestPartial = list[0].trim()
                            currentPartialText = bestPartial
                        }
                    }

                    override fun onResults(results: Bundle?) {
                        val list = results?.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                        if (!list.isNullOrEmpty() && list[0].isNotBlank()) {
                            finalRecognized = list[0].trim()
                        } else if (bestPartial.isNotBlank()) {
                            finalRecognized = bestPartial
                        }
                        latch.countDown()
                    }

                    override fun onError(error: Int) {
                        if (bestPartial.isNotBlank()) {
                            finalRecognized = bestPartial
                        }
                        latch.countDown()
                    }

                    override fun onEvent(eventType: Int, params: Bundle?) {}
                })

                val intent = android.content.Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH).apply {
                    putExtra(
                        RecognizerIntent.EXTRA_LANGUAGE_MODEL,
                        RecognizerIntent.LANGUAGE_MODEL_FREE_FORM
                    )
                    putExtra(RecognizerIntent.EXTRA_LANGUAGE, localeCode)
                    putExtra(RecognizerIntent.EXTRA_LANGUAGE_PREFERENCE, localeCode)
                    putExtra(RecognizerIntent.EXTRA_PARTIAL_RESULTS, true)
                    putExtra(RecognizerIntent.EXTRA_MAX_RESULTS, 1)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE, readSide)
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_CHANNEL_COUNT, 1)
                    putExtra(
                        RecognizerIntent.EXTRA_AUDIO_SOURCE_ENCODING,
                        AudioFormat.ENCODING_PCM_16BIT
                    )
                    putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_SAMPLING_RATE, 16000)
                }
                sr.startListening(intent)
            } catch (_: Exception) {
                latch.countDown()
            }
        }

        val writerThread = Thread {
            try {
                Thread.sleep(250)
                ParcelFileDescriptor.AutoCloseOutputStream(writeSide).use { out ->
                    RandomAccessFile(pcmFile, "r").use { raf ->
                        raf.seek(chunk.byteOffset)
                        var remaining = chunk.byteLength
                        val block = ByteArray(6400) // 200ms ở tần số 16kHz
                        while (remaining > 0 && !cancelRequested) {
                            val toRead = remaining.coerceAtMost(block.size)
                            val read = raf.read(block, 0, toRead)
                            if (read <= 0) break
                            out.write(block, 0, read)
                            out.flush()
                            remaining -= read
                            Thread.sleep(85)
                        }
                        // Truyền 1.0 giây khoảng lặng theo nhịp thực để bộ nhận diện chốt câu trước khi đóng ống
                        val silenceBlock = ByteArray(6400)
                        for (s in 0 until 5) {
                            if (cancelRequested) break
                            out.write(silenceBlock)
                            out.flush()
                            Thread.sleep(90)
                        }
                    }
                }
            } catch (_: Exception) {
            }
        }
        writerThread.start()

        latch.await(20, TimeUnit.SECONDS)

        mainHandler.post {
            try {
                recognizerRef?.stopListening()
                recognizerRef?.destroy()
            } catch (_: Exception) {
            }
            try {
                readSide.close()
            } catch (_: Exception) {
            }
        }

        return finalRecognized.ifBlank { bestPartial }
    }

    /**
     * Tự động trích xuất:
     * - Nếu là Độc thoại 1 người nói (MONOLOGUE): Chỉ tạo Tóm tắt ý chính, KHÔNG tạo Bảng phân công nhiệm vụ giả.
     * - Nếu là Cuộc họp nhiều người (MEETING): Tạo Kết luận cuộc họp & Bảng phân công nhiệm vụ.
     */
    private fun synthesizeConclusionsAndActions(fileName: String, durationSec: Int) {
        extractedConclusions.clear()
        extractedActions.clear()

        if (detectedDocumentType == "MONOLOGUE") {
            // Chế độ 01 người nói (Độc thoại / Ghi chú âm thanh): Chỉ tóm tắt nội dung, không tạo bảng giao việc giả
            for (turn in transcribedTurns.take(4)) {
                val content = turn["content"] ?: continue
                val ts = turn["timestamp"] ?: ""
                extractedConclusions.add("[$ts] $content")
            }
            return
        }

        val conclusionKeywords = listOf(
            "thống nhất", "kết luận", "đồng ý", "phê duyệt", "chốt", "như vậy", "tóm lại",
            "yêu cầu", "đề nghị", "agree", "conclude", "decided", "approved", "beschlossen"
        )
        val actionKeywords = listOf(
            "giao", "phân công", "phụ trách", "hoàn thành", "thực hiện", "báo cáo", "nộp",
            "gửi", "trước ngày", "trong tuần", "deadline", "assign", "verantwortlich"
        )

        for (turn in transcribedTurns) {
            val content = turn["content"] ?: continue
            val ts = turn["timestamp"] ?: ""
            val lower = content.lowercase(Locale.getDefault())

            if (conclusionKeywords.any { lower.contains(it) }) {
                extractedConclusions.add("[$ts] $content")
            }
            if (actionKeywords.any { lower.contains(it) } && extractedActions.size < 8) {
                extractedActions.add(
                    mapOf(
                        "task" to content,
                        "assignee" to (turn["speaker"] ?: "Người nói phụ trách"),
                        "coordinator" to "Các thành viên dự họp",
                        "deadline" to "Theo tiến độ (Mốc $ts)"
                    )
                )
            }
        }

        if (extractedConclusions.isEmpty() && transcribedTurns.isNotEmpty()) {
            val lastTurns = transcribedTurns.takeLast(2)
            for (t in lastTurns) {
                extractedConclusions.add("[Tổng hợp tại mốc ${t["timestamp"]}]: ${t["content"]}")
            }
        }

        if (extractedActions.isEmpty() && transcribedTurns.isNotEmpty()) {
            extractedActions.add(
                mapOf(
                    "task" to "Triển khai các nội dung đã thảo luận trong cuộc họp (Từ tệp ghi âm: $fileName - Thời lượng: ${formatDuration(durationSec)})",
                    "assignee" to "Các thành viên tham gia cuộc họp",
                    "coordinator" to "Thư ký cuộc họp",
                    "deadline" to "Theo kế hoạch"
                )
            )
        }
    }

    private fun buildAutoMeetingJson(
        audioFile: File,
        durationSec: Int,
        docLanguageMode: String
    ): JSONObject {
        val baseTitle = audioFile.nameWithoutExtension
            .removePrefix("Imported_")
            .replace("_", " ")
            .trim()
        val fmtDate = SimpleDateFormat("dd/MM/yyyy", Locale.getDefault()).format(Date(audioFile.lastModified()))
        val fmtTime = SimpleDateFormat("HH 'giờ' mm 'phút' 'ngày' dd/MM/yyyy", Locale.getDefault())
            .format(Date(audioFile.lastModified()))

        val turnsJson = JSONArray()
        for (t in transcribedTurns) {
            val obj = JSONObject()
            obj.put("speaker", t["speaker"] ?: "Người nói #1")
            obj.put("lang", t["lang"] ?: "VI")
            obj.put("timestamp", t["timestamp"] ?: "")
            obj.put("content", t["content"] ?: "")
            obj.put("translation", t["translation"] ?: "")
            turnsJson.put(obj)
        }

        val concJson = JSONArray()
        for (c in extractedConclusions) {
            concJson.put(c)
        }

        val actJson = JSONArray()
        for (a in extractedActions) {
            val obj = JSONObject()
            obj.put("task", a["task"] ?: "")
            obj.put("assignee", a["assignee"] ?: "")
            obj.put("coordinator", a["coordinator"] ?: "")
            obj.put("deadline", a["deadline"] ?: "")
            actJson.put(obj)
        }

        val isMonologue = detectedDocumentType == "MONOLOGUE"

        return JSONObject().apply {
            put("docLanguageMode", docLanguageMode)
            put("documentType", detectedDocumentType)
            put("detectedSpeakerCount", detectedSpeakerCount)
            put("diarizationReport", diarizationReport)
            put("governingBody", "")
            put("organizationName", "ANH'S TEAM")
            put("documentNumber", if (isMonologue) "Số: 01/2026/GB-AT" else "Số: 01/2026/BB-AT")
            put("locationDate", "Ngày $fmtDate")
            put(
                "meetingTitle",
                if (isMonologue) "BẢN GỠ BĂNG & TÓM TẮT NỘI DUNG GHI ÂM" else "BIÊN BẢN CUỘC HỌP"
            )
            put(
                "meetingSubject",
                if (isMonologue) {
                    "Bản ghi độc thoại (01 người nói - Không phải biên bản họp): $baseTitle (Thời lượng: ${formatDuration(durationSec)})"
                } else {
                    "Biên bản cuộc họp ($detectedSpeakerCount giọng nói khác nhau): $baseTitle (Thời lượng: ${formatDuration(durationSec)})"
                }
            )
            put("startTime", fmtTime)
            put("endTime", "Sau ${formatDuration(durationSec)} ghi âm cùng ngày")
            put("venue", "Tệp nguồn: ${audioFile.name}")
            put("chairName", if (isMonologue) "Người nói duy nhất" else "Người nói #1 (Chủ trì)")
            put("chairTitle", if (isMonologue) "Độc thoại" else "Chủ tọa")
            put("secretaryName", "Hệ thống Tự động Anh's TEAM")
            put("secretaryTitle", "Tổng hợp tự động")
            put(
                "attendeesList",
                if (isMonologue) {
                    "Chỉ có 01 người nói duy nhất ($diarizationReport)"
                } else {
                    "Phát hiện $detectedSpeakerCount người nói khác nhau ($diarizationReport)"
                }
            )
            put("speakerTurns", turnsJson)
            put("conclusions", concJson)
            put("actionItems", actJson)
        }
    }

    private fun formatDuration(totalSec: Int): String {
        val hrs = totalSec / 3600
        val mins = (totalSec % 3600) / 60
        val secs = totalSec % 60
        return String.format(Locale.US, "%02d:%02d:%02d", hrs, mins, secs)
    }
