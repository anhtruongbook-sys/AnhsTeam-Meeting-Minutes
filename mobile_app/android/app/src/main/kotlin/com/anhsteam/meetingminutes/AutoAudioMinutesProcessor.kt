/**
 * Động cơ Tự Động Hóa Toàn Trình (v1.5.0):
 * 1. Giải mã siêu tốc (.m4a, .mp3, .wav, .aac, .ogg, .3gp, .amr) -> 16kHz 16-bit Mono PCM.
 * 2. Phân tách đoạn thoại VAD + Phân tích Sinh trắc Giọng nói Âm học (Acoustic Speaker Diarization:
 *    Tần số cơ bản F0 bằng Tự tương quan Autocorrelation + Độ sáng âm sắc Spectral Brightness + ZCR).
 * 3. Tự động phân biệt:
 *    - Bản ghi CHỈ 01 NGƯỜI NÓI (Độc thoại / Ghi chú / Bài nói cá nhân -> KHÔNG PHẢI BIÊN BẢN HỌP)
 *    - Bản ghi NHIỀU NGƯỜI NÓI (2+ giọng nói khác nhau -> BIÊN BẢN CUỘC HỌP ĐA NGƯỜI NÓI).
 * 4. Tự động gỡ băng (Speech-to-Text) và xuất file Word (.docx) đúng thể thức tương ứng.
 */
class AutoAudioMinutesProcessor(private val context: Context) {

    data class VoiceSignature(
        val pitchHz: Double,
        val zcrHz: Double,
        val spectralBrightness: Double,
        val rmsEnergy: Int,
        val voicedRatio: Double
    )

    data class SpeechChunk(
        val index: Int,
        val startSec: Int,
        val endSec: Int,
        val byteOffset: Long,
        val byteLength: Int,
        val signature: VoiceSignature,
        var speakerClusterId: Int = 1,
        var speakerVoiceDesc: String = ""
    )

    data class SpeakerCluster(
        val id: Int,
        var meanPitchHz: Double,
        var meanBrightness: Double,
        var meanZcrHz: Double,
        var chunkCount: Int = 0,
        var totalDurationSec: Int = 0
    ) {
        fun voiceProfileLabel(): String {
            val f0 = meanPitchHz.toInt()
            val tone = when {
                meanPitchHz < 125.0 -> "Giọng Nam trầm (~${f0}Hz)"
                meanPitchHz < 165.0 -> "Giọng Nam trung / Trầm (~${f0}Hz)"
                meanPitchHz < 195.0 -> "Giọng Trung cao (~${f0}Hz)"
                else -> "Giọng Nữ / Cao (~${f0}Hz)"
            }
            return tone
        }
    }

